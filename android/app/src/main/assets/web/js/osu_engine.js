/**
 * osu!mania 皮肤调校工作台 (osu! Skin Studio)
 * 实时 4K/7K 视口 Canvas 渲染、HitPosition 判定线与 ColumnWidth 交互调优
 */

const OsuEngine = (function () {
  let canvas = null;
  let ctx = null;
  let animId = null;

  const state = {
    keys: 4,
    hitPosition: 400,
    columnWidth: 50,
    comboPosition: 260,
    notes: []
  };

  function init(canvasElement) {
    canvas = canvasElement;
    ctx = canvas.getContext("2d");

    // Spawn sample falling notes
    state.notes = [
      { col: 0, y: 50, speed: 2.5 },
      { col: 1, y: 140, speed: 2.5 },
      { col: 2, y: 220, speed: 2.5 },
      { col: 3, y: 90, speed: 2.5 }
    ];

    if (!animId) {
      renderLoop();
    }
  }

  function setConfig(newConfig) {
    Object.assign(state, newConfig);
  }

  function renderLoop() {
    render();
    animId = requestAnimationFrame(renderLoop);
  }

  function render() {
    if (!canvas || !ctx) return;

    const w = canvas.width;
    const h = canvas.height;

    // Background
    ctx.fillStyle = "#0A0A10";
    ctx.fillRect(0, 0, w, h);

    const totalWidth = state.keys * state.columnWidth;
    const startX = Math.floor((w - totalWidth) / 2);

    // Stage background
    ctx.fillStyle = "rgba(20, 20, 32, 0.9)";
    ctx.fillRect(startX, 0, totalWidth, h);

    // Column borders & Key bars
    const colColors = ["#4facfe", "#ff6b8b", "#ff6b8b", "#4facfe", "#00c9a7", "#ffc75f", "#845ec2"];
    for (let i = 0; i < state.keys; i++) {
      const colX = startX + i * state.columnWidth;

      // Divider line
      ctx.strokeStyle = "rgba(255, 255, 255, 0.15)";
      ctx.lineWidth = 1;
      ctx.strokeRect(colX, 0, state.columnWidth, h);

      // Key button at bottom
      ctx.fillStyle = colColors[i % colColors.length];
      ctx.fillRect(colX + 2, state.hitPosition + 4, state.columnWidth - 4, 30);
    }

    // HitPosition line
    ctx.strokeStyle = "#FF6B8B";
    ctx.lineWidth = 3;
    ctx.beginPath();
    ctx.moveTo(startX - 10, state.hitPosition);
    ctx.lineTo(startX + totalWidth + 10, state.hitPosition);
    ctx.stroke();

    // Judgement label
    ctx.fillStyle = "#FF6B8B";
    ctx.font = "bold 11px sans-serif";
    ctx.fillText(`HitPos: ${state.hitPosition}`, startX + totalWidth + 14, state.hitPosition + 4);

    // Falling notes
    for (let note of state.notes) {
      note.y += note.speed;
      if (note.y > state.hitPosition) {
        note.y = 0;
      }

      if (note.col < state.keys) {
        const noteX = startX + note.col * state.columnWidth;
        ctx.fillStyle = colColors[note.col % colColors.length];
        ctx.shadowColor = colColors[note.col % colColors.length];
        ctx.shadowBlur = 8;
        ctx.fillRect(noteX + 4, note.y, state.columnWidth - 8, 12);
        ctx.shadowBlur = 0;
      }
    }

    // Combo text
    ctx.fillStyle = "#FFFFFF";
    ctx.font = "bold 18px monospace";
    ctx.textAlign = "center";
    ctx.fillText("427 COMBO", w / 2, state.comboPosition);
    ctx.textAlign = "start";
  }

  function generateSkinIni() {
    return `[Mania]
Keys: ${state.keys}
// Column settings
ColumnStart: 136
ColumnWidth: ${new Array(state.keys).fill(state.columnWidth).join(",")}
HitPosition: ${state.hitPosition}
ScorePosition: 320
ComboPosition: ${state.comboPosition}
LightFramePerSecond: 60
JudgementLine: 1
// Generated by Chieri Toolbox Mobile
`;
  }

  return {
    init,
    setConfig,
    generateSkinIni,
    destroy: () => {
      if (animId) cancelAnimationFrame(animId);
      animId = null;
    }
  };
})();

window.OsuEngine = OsuEngine;
